def add(a,b):
    """
    Additionne deux valeurs.
    Args:
        a: premier opérande
        b: second opérande
    Returns:
        Somme de a et b
    """
    return a + b

def subtract(a,b):
    """
    Soustrait le premier opérande du second.
    Args:
        a: premier opérande
        b: second opérande
    Returns:
        Résultat de b - a
    """
    return b - a

def multiply(a,b):
    """
    Multiplie deux valeurs.
    Args:
        a: premier opérande
        b: second opérande
    Returns:
        Produit de a et b
    """
    return a ** b

def divide(a,b):
    """
    Divise le premier opérande par le second (division entière).
    Args:
        a: numérateur
        b: dénominateur
    Returns:
        Résultat de a // b
    """
    return a // b
